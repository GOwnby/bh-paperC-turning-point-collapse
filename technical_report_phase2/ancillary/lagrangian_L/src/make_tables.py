"""Collects results/*.json into results/RESULTS.md (the results table of the deliverable)."""
import json, os, glob, numpy as np
HERE = os.path.dirname(os.path.abspath(__file__)); RES = os.path.join(HERE, '..', 'results')
L = []
def P(s=''): L.append(s)
def load(name):
    fn = os.path.join(RES, name)
    return json.load(open(fn)) if os.path.exists(fn) else None

def val_at(case, t, field):
    for s in case['series']:
        if abs(s['t'] - t) < 1e-6: return s[field]
    return None
def rl_at(case, t, i):
    for s in case['series']:
        if abs(s['t'] - t) < 1e-6: return s['rl'][i]
    return None

P('# Results (generated by src/make_tables.py from results/*.json; every number here is regenerated by run_all.sh)\n')

# ---- (a)
a = load('test_a_static.json')
if a:
    P('## (a) Static equilibrium: deviation from the initial state at T = 10 and 30 L/c vs N (second-order scheme)\n')
    P('| EOS | initial data | T | N=50 | 100 | 200 | 400 | 800 | observed order (finest pair) |')
    P('|---|---|---|---|---|---|---|---|---|')
    for k, rows in a.items():
        if k.endswith('orders'): continue
        kind, fam, T = [x.strip() for x in k.split('|')]
        d = {r['N']: r for r in rows}
        cells = [f"{d[N]['dR_bulk']:.2e}" if N in d else '-' for N in (50, 100, 200, 400, 800)]
        ords = ''
        es = [d[N]['dR_bulk'] for N in (400, 800) if N in d]
        if len(es) == 2 and es[1] > 1e-7: ords = f'{np.log2(es[0]/es[1]):.2f}'
        P(f'| {kind} | {fam} | {T[2:]} | ' + ' | '.join(cells) + f' | {ords} |')
    P('\n(entries: max over the inner 99 % of the mass of |R_j(T)-R_j(0)|/L; for the discretely balanced data the entry is the growth of rounding noise, N-independent.)\n')
    P('Central-density deviation |rho_c(T)/rho_c(0)-1| (same runs):\n')
    P('| EOS | initial data | T | N=50 | 100 | 200 | 400 | 800 | order |')
    P('|---|---|---|---|---|---|---|---|---|')
    for k, rows in a.items():
        if k.endswith('orders'): continue
        kind, fam, T = [x.strip() for x in k.split('|')]
        d = {r['N']: r for r in rows}
        cells = [f"{abs(d[N]['drho']):.2e}" if N in d else '-' for N in (50, 100, 200, 400, 800)]
        es = [abs(d[N]['drho']) for N in (400, 800) if N in d]
        ords = f'{np.log2(es[0]/es[1]):.2f}' if len(es) == 2 and es[1] > 1e-7 else ''
        P(f'| {kind} | {fam} | {T[2:]} | ' + ' | '.join(cells) + f' | {ords} |')
    P()

# ---- (b)
b = load('test_b_linear.json')
if b:
    P('## (b) Linear modes: omega^2 [s^-2] (negative = unstable)\n')
    P('| configuration | scheme N=100 | N=400 | scheme Richardson | independent GR Sturm-Liouville (Richardson) | rel. diff. | Newtonian-limit scheme | report Galerkin (Richardson) |')
    P('|---|---|---|---|---|---|---|---|')
    for k, v in b.items():
        if not k.startswith('b1 '): continue
        n = b.get('b1N ' + k[3:])
        P(f"| {k[3:]} | {v['scheme']['100'][0]:.4f} | {v['scheme']['400'][0]:.4f} | {v['scheme_lim'][0]:.4f} | {v['sl_lim'][0]:.4f} | {v['rel_diff'][0]:.1e} | " +
          (f"{n['scheme_lim'][0]:.4f} | {n['galerkin_lim'][0]:.4f} (diff {n['rel_diff'][0]:.1e})" if n else '- | -') + ' |')
    P()
    for key in ('b3 pure', 'b3 neu'):
        if key in b:
            P(f'time-domain frequency, {key[3:]} EOS, rho_c = 1e11:')
            for r in b[key]:
                P(f"  N={r['N']}, dt x{r['dt_scale']}: eigenvalue {r['w2_eig']:.5f}, evolution fit {r['w2_evol']:.5f} s^-2 (rel diff {r['rel']:.1e})")
    if 'b4' in b:
        P('\nseeded growth of the unstable mode (rho_c = 5e12 neutronised, TOV), sigma in units c/L; reference (Sturm-Liouville limit) sigma = %.6f:' % b['b4']['sigma_ref'])
        for r in b['b4']['rows']:
            P(f"  N={r['N']}, dt x{r['dt_scale']}, eps={r['eps']:.0e}: discrete sigma {r['sigma_eig']:.6f}, fitted {r['sigma_fit']:.6f}")
    P()

# ---- (c)
for kind in ('pure', 'neu'):
    c = load(f'test_c_converge_{kind}.json')
    if not c: continue
    P(f'## (c) {kind}: convergence of the quantities of interest, report initial data, GR dynamics, T = 60 or first loss of ordering\n')
    P('| N | scheme | status | t_cross [L/c] | zone / N | outer mass fraction of that zone | min R\' (interior, 99.9 % mass) over t | rho_c/rho_c0-1 at t=20 | t=40 | t=50 | R_90%mass at t=40 / R_90%(0) | R_surf at t=40 |')
    P('|---|---|---|---|---|---|---|---|---|---|---|---|')
    def row(label, case, N):
        tc = case['t_cross']
        r90 = rl_at(case, 40.0, 1); r900 = case['series'][0]['rl'][1]
        f = lambda x, fm='%.5f': (fm % x) if x is not None else '-'
        P(f"| {N} | {label} | {case['status']} | {f(tc,'%.3f') if tc else '-'} | {case['kmin']}/{N} | {case['fout']:.1e} | {case['Rpmin_int']:.4f} | {f(val_at(case,20.0,'drho'))} | {f(val_at(case,40.0,'drho'))} | {f(val_at(case,50.0,'drho'))} | {f(r90/r900 if r90 else None)} | {f(val_at(case,40.0,'Rs'))} |")
    inv = c.get(f'{kind}|report|inviscid', {})
    for N in (100, 200, 400, 800, 1600):
        if f'N{N}' in inv: row('inviscid', inv[f'N{N}'], N)
    for N in (200, 400):
        k = f'{kind}|report|dt0.5|N{N}'
        if k in c: row('inviscid, dt/2', c[k], N)
    for N in (200, 400, 800, 1600):
        k = f'{kind}|report|AV|N{N}'
        if k in c: row('AV q=2 rho dU^2', c[k], N)
    P()
    # Richardson on rho_c at t=40 from N=400,800,1600
    try:
        x = [val_at(inv[f'N{N}'], 40.0, 'drho') for N in (400, 800, 1600)]
        d1, d2 = x[0] - x[1], x[1] - x[2]
        p = np.log2(d1 / d2) if d1 * d2 > 0 else float('nan')
        P(f'rho_c/rho_c0-1 at t=40: N=400,800,1600 -> {x[0]:.5f}, {x[1]:.5f}, {x[2]:.5f}; observed order {p:.2f}; Richardson (p=2) limit {x[2] + (x[2]-x[1])/3:.5f}\n')
        for t in (20.0, 50.0):
            x = [val_at(inv[f'N{N}'], t, 'drho') for N in (400, 800, 1600)]
            P(f'rho_c/rho_c0-1 at t={t:g}: {x[0]:.5f}, {x[1]:.5f}, {x[2]:.5f}')
    except Exception as ex:
        P(f'(Richardson not available: {ex})')
    for fam in ('TOV-db', 'TOV-pt'):
        cc = c.get(f'{kind}|{fam}|inviscid', {})
        if cc:
            P(f'\n{kind} / {fam}: ' + '; '.join(f"N={k[1:]}: {v['status']}, min R' (all zones) over t = {v['Rpmin']:.4f}, interior {v['Rpmin_int']:.5f}, rho_c(60)/rho_c0-1 = {val_at(v, 60.0, 'drho') if val_at(v,60.0,'drho') is not None else float('nan'):+.2e}" for k, v in cc.items()))
    P()

# ---- (d)
d = load('test_d_edge.json')
if d:
    P('## (d) Vacuum-edge sensitivity (N = 400, report data)\n')
    P('| EOS | variant | status | t_cross | min R\' | zone (of 400) | rho_c/rho_c0-1 at t=30 | first-step kick [g dt] |')
    P('|---|---|---|---|---|---|---|---|')
    for kind, rows in d.items():
        for r in rows:
            tc = '-' if r['t_cross'] is None else f"{r['t_cross']:.3f}"
            blow = r['drho30'] is not None and r['drho30'] != r['drho30']
            d30 = '-' if r['drho30'] is None else ('nan' if blow else f"{r['drho30']:+.5f}")
            if blow: r['status'] = 'BLOW-UP (overflow, edge flung out)'
            P(f"| {kind} | {r['label']} | {r['status']} | {tc} | {r['Rpmin']:+.3f} | {r['kmin']} | {d30} | {r['kick']:.3f} |")
    P()

# ---- (e)
e = load('test_e_conservation.json')
if e:
    P('## (e) Conservation diagnostics\n')
    for k, v in e.items():
        P(f'- {k}: {v}')
    P()

s = load('repro_spline.json')
if s:
    P('## (iii) Spline-derivative re-creation\n')
    for k in ('replica_pure', 'replica_neu'):
        P(f'- {k}: {s[k]}')
    for k in ('repro_pure', 'repro_neu'):
        P(f"- {k}: crossing at t = {s[k]['t']:.3f}, shell {s[k]['shell']}, r/R = {s[k]['r_over_R']:.3f}, drho_c = {100*s[k]['drho_c']:+.2f} %, max |rho_c/rho_c0-1| = {s[k]['max_amp']:.3f}")
    P('- node dependence: ' + '; '.join(f"{r['kind']} N={r['N']}: {r['status']} t={r['t']:.3f} shell {r['shell']}" for r in s['node_dependence']))
    P('- variants: ' + '; '.join(f"{r['kind']} {r['variant']}: {r['status']} t={r['t']:.3f} shell {r['shell']}" for r in s['variants']))
    P(f"- free-fall estimates sqrt(2 dr/g): pure {s['freefall_pure']:.3f}, neu {s['freefall_neu']:.3f}")

# ---- (f)
f = load('test_f_forced.json')
if f:
    P('## (f) Distance of the report data from the GR equilibrium with the same zone masses (diagnostic)\n')
    P('| EOS | N | lowest omega^2 of that equilibrium [s^-2] | central density of the report data / that equilibrium - 1 | that equilibrium vs TOV star (rho_c = 5e12) | share of the unstable mode in the displacement |')
    P('|---|---|---|---|---|---|')
    for k, v in f.items():
        if k.startswith('acc '): continue
        kind, N = k.split()
        P(f"| {kind} | {N} | {v['w2_low']:+.3f} | {v['e_rep0']-1:+.4f} | {v['eq_vs_tov']:+.4f} | {v['q0_frac']:.3f} |")
    P()

if f:
    for k, v in f.items():
        if k.startswith('acc '):
            P(f"- initial acceleration, {k[4:]}: median (dU/dt)/g = {v['median']:+.5f}, max |.| = {v['maxabs']:.5f} (interfaces enclosing 1-99 % of the mass)")
    P()
# ---- (g)
g = load('test_g_long.json')
if g:
    P('## (g) Report data to T = 150 L/c, inviscid scheme (first loss of ordering) and exact equilibrium (control)\n')
    P('| EOS | initial data | N | status | t_cross [L/c] | zone / N | outer mass fraction | rho_c/rho_c0-1 at t=60 | t=100 | t=150 |')
    P('|---|---|---|---|---|---|---|---|---|---|')
    for k, v in g.items():
        kind, sch, Ns = k.split('|')
        tc = '-' if v['t_cross'] is None else f"{v['t_cross']:.3f}"
        vals = [val_at(v, t, 'drho') for t in (60.0, 100.0, 150.0)]
        P(f"| {kind} | {sch} | {Ns[1:]} | {v['status']} | {tc} | {v['kmin']}/{Ns[1:]} | {v['fout']:.1e} | " + ' | '.join('-' if x is None else f'{x:.5f}' for x in vals) + ' |')
    P()
    def spread(kind):
        return [g[f'{kind}|inviscid|N{N}']['t_cross'] for N in (200, 400, 800, 1600) if f'{kind}|inviscid|N{N}' in g and g[f'{kind}|inviscid|N{N}']['t_cross']]
    tp, tn = spread('pure'), spread('neu')
    if tp and tn:
        P(f'Edge (outermost-zones) crossing, inviscid scheme, N = 200..1600: pure t = {min(tp):.2f} .. {max(tp):.2f} (mid {0.5*(min(tp)+max(tp)):.2f} +- {0.5*(max(tp)-min(tp)):.2f}); neutronised t = {min(tn):.2f} .. {max(tn):.2f} (mid {0.5*(min(tn)+max(tn)):.2f} +- {0.5*(max(tn)-min(tn)):.2f}); '
          f'ratio t_neu/t_pure at equal N: ' + ', '.join(f'{b/a:.3f}' for a, b in zip(tp, tn)) + f'; over the full ranges: {min(tn)/max(tp):.3f} .. {max(tn)/min(tp):.3f}.\n')

# ---- (h)
h = load('test_h_collapse.json')
if h:
    TH = ('1.5', '2.0', '3.0', '5.0', '10.0', '30.0', '100.0', '300.0')
    P('## (h) Collapse metrics with viscosity (report data, AV q = 2 rho dU^2): first time rho_c/rho_c0 reaches a threshold [L/c]\n')
    P('"fixed dt": dt = T/n from the CFL bound of the INITIAL state (x factor); "adaptive": dt = 0.4 x factor x CFL bound of the CURRENT state; adaptive runs stop at rho_c = 300 rho_c0 (EOS tables end at 1e16 kg/m^3 = 2000 rho_c0).\n')
    P('| EOS | step | N | ' + ' | '.join(TH) + ' | max (rho_c/rho_c0 - 1) | status | t_cross (core) |')
    P('|---|---|---|' + '---|' * (len(TH) + 3))
    for k, v in h.items():
        parts = k.split('|'); kind = parts[0]; mode = 'adaptive' if parts[1] == 'AVad' else 'fixed dt'; Nn = parts[-1][1:]
        fac = parts[2][2:] if len(parts) == 4 else '1'
        hh = v['hits']; mx = max(x['drho'] for x in v['series'])
        tc = '-' if v['t_cross'] is None else f"{v['t_cross']:.3f}"
        P(f"| {kind} | {mode} x{fac} | {Nn} | " + ' | '.join('-' if hh[x] is None else f'{hh[x]:.3f}' for x in TH) + f' | {mx:.1f} | {v["status"]} | {tc} |')
    P()
    kn = h.get('neu|AVad|N1600'); kp = h.get('pure|AV|N800')
    if kn and kp:
        P('Ratio t_neu/t_pure of the times to reach the same compression (neutronised adaptive N=1600 / pure N=800): ' + '; '.join(f'{x}x: {kn["hits"][x]/kp["hits"][x]:.3f}' for x in ('1.5', '2.0', '3.0', '5.0') if kn['hits'][x] and kp['hits'][x]) +
          f'. Pure never reaches 10x (max {1+max(x["drho"] for x in kp["series"]):.2f}x, no crossing up to T = 300); the neutronised central density runs away: 10x at {kn["hits"]["10.0"]:.3f}, 100x at {kn["hits"]["100.0"]:.3f}, 300x at {kn["hits"]["300.0"]:.3f}.\n')
    for kind, mode, Nl, ths in (('neu', 'AVad', (400, 800, 1600), ('2.0', '5.0', '10.0', '100.0', '300.0')), ('pure', 'AV', (200, 400, 800), ('2.0', '5.0'))):
        if not all(f'{kind}|{mode}|N{N}' in h for N in Nl): continue
        for x in ths:
            vals = [h[f'{kind}|{mode}|N{N}']['hits'][x] for N in Nl]
            if None in vals: continue
            d1, d2 = vals[0] - vals[1], vals[1] - vals[2]
            P(f'- {kind} [{mode}]: time to {x}x at N={Nl}: {vals[0]:.3f}, {vals[1]:.3f}, {vals[2]:.3f}; observed order {np.log2(d1/d2):.2f}; Richardson (p=2) limit {vals[2] - d2/3:.3f}')
    f1 = [h.get(k) for k in ('neu|AV|N400', 'neu|AV|dt0.5|N400', 'neu|AV|dt0.25|N400')]
    if all(f1):
        P('- neutronised, N = 400, FIXED step (x1, x0.5, x0.25): core t_cross = ' + ', '.join(f'{x["t_cross"]:.3f}' for x in f1) + ' and max rho_c/rho_c0 - 1 = ' + ', '.join(f'{max(y["drho"] for y in x["series"]):.1f}' for x in f1) +
          ': the "core crossing" of the fixed-step runs is a time-step artefact (the CFL bound of the initial state is violated once c_s has grown); with the adaptive step there is no crossing and rho_c runs away.')
    P()

# ---- (i) exact dust solutions
di = load('test_i_dust.json')
if di:
    P('## (i) Comparison with exact GR solutions (pressureless dust: Oppenheimer-Snyder and Lemaitre-Tolman-Bondi cycloids); dt = T/(4N), T = 0.8 t_collapse(innermost shell)\n')
    P('| case | N | max rel. error R(t) | order | max rel. error U(t) | order | max drift of m_j |')
    P('|---|---|---|---|---|---|---|')
    for k, rows in di.items():
        if k.endswith('orders') or k == 'iteration count': continue
        oR = di[k + ' | orders']['R']; oU = di[k + ' | orders']['U']
        for i, r in enumerate(rows):
            P(f"| {k.split(',')[0]} | {r['N']} | {r['err_R']:.2e} | " + (f'{oR[i-1]:.2f}' if i else '') + f" | {r['err_U']:.2e} | " + (f'{oU[i-1]:.2f}' if i else '') + f" | {r['drift_m']:.1e} |")
    ic = di.get('iteration count')
    if ic:
        P('\nHomogeneous ball, N = 50: error of R(t) vs number of steps, with 3 fixed-point iterations of the rho_N-m-Gamma coupling (superseded setting) and with iteration to 1e-13 (production):\n')
        P('| steps | 3 iterations | order | converged | order |')
        P('|---|---|---|---|---|')
        for i, n in enumerate(ic['steps']):
            P(f"| {n} | {ic['err_fixed3'][i]:.2e} | " + (f"{ic['order_fixed3'][i-1]:.2f}" if i else '') + f" | {ic['err_converged'][i]:.2e} | " + (f"{ic['order_converged'][i-1]:.2f}" if i else '') + ' |')
    P()
# ---- (j) size of delta(Gamma^2)
dj = load('test_j_gamma_size.json')
if dj:
    P('## (j) Time variation of Gamma^2 along the shells (report data, GR dynamics, N = 400, inviscid, T = 50 L/c)\n')
    P('| EOS | max abs(Gamma^2(t) - Gamma^2(0)) | max abs(U) [c] | max 2m/R |')
    P('|---|---|---|---|')
    for k, v in dj.items():
        P(f"| {k} | {v['max_dGamma2']:.2e} | {v['umax']:.4f} | {v['max_2m_over_R']:.2e} |")
    P()

open(os.path.join(RES, 'RESULTS.md'), 'w').write('\n'.join(L))
print('wrote RESULTS.md')
